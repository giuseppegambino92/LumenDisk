//! Feature 1 — Ghost Shield: zero-dotfile virtualisation.
//!
//! macOS litters foreign volumes with `.DS_Store`, AppleDouble `._*` files (the NFS client
//! stores extended attributes / resource forks in them), `.Spotlight-V100`, `.Trashes`,
//! `.fseventsd`, `.TemporaryItems`, … Ghost Shield intercepts every create/write/rename of
//! such names and keeps them in a per-volume SQLite vault
//! (`~/Library/Application Support/LumenDisk/GhostVault/<uuid>.db`). Finder sees its files
//! as usual; the physical disk never receives a single byte of them. Pre-existing junk on the
//! disk is hidden while the shield is active.

use std::collections::{BTreeMap, HashMap};
use std::path::{Path, PathBuf};

use super::*;

/// Ghost inode numbers live far above any driver's inode space.
pub const GHOST_BASE: Ino = 1 << 62;

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct GhostRules {
    pub ds_store: bool,
    pub apple_double: bool,
    pub spotlight: bool,
    pub trashes: bool,
    pub fseventsd: bool,
    pub other: bool,
}

impl Default for GhostRules {
    fn default() -> Self {
        GhostRules { ds_store: true, apple_double: true, spotlight: true, trashes: true, fseventsd: true, other: true }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Category {
    DsStore,
    AppleDouble,
    Spotlight,
    Trashes,
    Fseventsd,
    Other,
}

/// Classify a file name as macOS junk.
pub fn classify(name: &str) -> Option<Category> {
    match name {
        ".DS_Store" => Some(Category::DsStore),
        ".Spotlight-V100" => Some(Category::Spotlight),
        ".Trashes" => Some(Category::Trashes),
        ".fseventsd" => Some(Category::Fseventsd),
        ".TemporaryItems" | ".DocumentRevisions-V100" | ".apdisk" | ".metadata_never_index"
        | ".metadata_never_index_unless_rootfs" | ".com.apple.timemachine.donotpresent" | ".VolumeIcon.icns_" => {
            Some(Category::Other)
        }
        n if n.starts_with("._") => Some(Category::AppleDouble),
        _ => None,
    }
}

impl GhostRules {
    fn allows(&self, c: Category) -> bool {
        match c {
            Category::DsStore => self.ds_store,
            Category::AppleDouble => self.apple_double,
            Category::Spotlight => self.spotlight,
            Category::Trashes => self.trashes,
            Category::Fseventsd => self.fseventsd,
            Category::Other => self.other,
        }
    }
}

#[derive(Clone, Debug, serde::Serialize)]
pub struct GhostEntry {
    pub path: String,
    pub size: u64,
    pub category: Category,
}

#[derive(Clone, Debug)]
struct GNode {
    parent: Ino,
    name: String,
    kind: FileKind,
    data: Vec<u8>,
    perm: u16,
    atime: Timestamp,
    mtime: Timestamp,
    ctime: Timestamp,
    children: BTreeMap<String, Ino>,
    /// Generated by LumenDisk (volume icon); never saved to the vault.
    synthetic: bool,
}

pub struct GhostShield<F: FileSystem> {
    pub inner: F,
    pub enabled: bool,
    pub rules: GhostRules,
    nodes: HashMap<Ino, GNode>,
    /// Ghost children of real directories.
    dir_children: HashMap<Ino, BTreeMap<String, Ino>>,
    /// Real inode → (parent, name), learned from lookups/readdir; used to compute vault paths.
    real_parent: HashMap<Ino, (Ino, String)>,
    next: u64,
    pub blocked_total: u64,
    uid: u32,
    gid: u32,
    vault_path: Option<PathBuf>,
    dirty: bool,
}

impl<F: FileSystem> GhostShield<F> {
    pub fn new(inner: F, enabled: bool, rules: GhostRules, defaults: MountDefaults, vault_path: Option<PathBuf>) -> Self {
        let mut g = GhostShield {
            inner,
            enabled,
            rules,
            nodes: HashMap::new(),
            dir_children: HashMap::new(),
            real_parent: HashMap::new(),
            next: 1,
            blocked_total: 0,
            uid: defaults.uid,
            gid: defaults.gid,
            vault_path,
            dirty: false,
        };
        if let Err(e) = g.load_vault() {
            eprintln!("lumendisk: ghost vault load failed: {e}");
        }
        g
    }

    fn is_ghost(ino: Ino) -> bool {
        ino >= GHOST_BASE
    }

    fn intercept(&self, name: &str) -> bool {
        self.enabled && classify(name).map(|c| self.rules.allows(c)).unwrap_or(false)
    }

    /// Does an operation on (parent, name) belong to the ghost world?
    fn ghost_ctx(&self, parent: Ino, name: &str) -> bool {
        Self::is_ghost(parent)
            || self.intercept(name)
            || self.dir_children.get(&parent).and_then(|c| c.get(name)).map(|i| self.nodes.get(i).map(|n| n.synthetic).unwrap_or(false)).unwrap_or(false)
    }

    /// Show a custom Finder volume icon without touching the disk: a virtual
    /// `.VolumeIcon.icns` plus a virtual `._.` AppleDouble whose FinderInfo carries
    /// kHasCustomIcon for the root folder. Skipped if the disk already has its own icon.
    pub fn install_volume_icon(&mut self, icns: Vec<u8>) {
        let root = self.inner.root_ino();
        if icns.is_empty() || self.inner.lookup(root, ".VolumeIcon.icns").is_ok() {
            return;
        }
        let add = |g: &mut Self, name: &str, data: Vec<u8>| {
            if let Some(old) = g.dir_children.get(&root).and_then(|c| c.get(name)).copied() {
                g.dir_children.get_mut(&root).unwrap().remove(name);
                g.nodes.remove(&old);
            }
            let ino = GHOST_BASE + g.next;
            g.next += 1;
            let now = Timestamp::now();
            g.nodes.insert(
                ino,
                GNode { parent: root, name: name.into(), kind: FileKind::File, data, perm: 0o644, atime: now, mtime: now, ctime: now, children: BTreeMap::new(), synthetic: true },
            );
            g.dir_children.entry(root).or_default().insert(name.into(), ino);
        };
        // Note: the macOS NFS client refuses extended attributes on a volume root (EPERM), so a
        // root FinderInfo "has custom icon" flag cannot be expressed over NFS; the app applies
        // the icon to its Desktop alias instead. The virtual icon file stays for other clients.
        add(self, ".VolumeIcon.icns", icns);
    }

    fn children(&self, parent: Ino) -> Option<&BTreeMap<String, Ino>> {
        if Self::is_ghost(parent) {
            self.nodes.get(&parent).map(|n| &n.children)
        } else {
            self.dir_children.get(&parent)
        }
    }

    fn children_mut(&mut self, parent: Ino) -> FsResult<&mut BTreeMap<String, Ino>> {
        if Self::is_ghost(parent) {
            let n = self.nodes.get_mut(&parent).ok_or(FsError::Stale)?;
            if n.kind != FileKind::Dir {
                return Err(FsError::NotDir);
            }
            Ok(&mut n.children)
        } else {
            Ok(self.dir_children.entry(parent).or_default())
        }
    }

    fn ghost_lookup(&self, parent: Ino, name: &str) -> FsResult<Ino> {
        self.children(parent).and_then(|c| c.get(name)).copied().ok_or(FsError::NotFound)
    }

    fn new_node(&mut self, parent: Ino, name: &str, kind: FileKind, perm: u16) -> FsResult<Ino> {
        check_name(name, 255)?;
        if self.children(parent).map(|c| c.contains_key(name)).unwrap_or(false) {
            return Err(FsError::Exists);
        }
        if !Self::is_ghost(parent) {
            // the real directory must exist
            let a = self.inner.getattr(parent)?;
            if a.kind != FileKind::Dir {
                return Err(FsError::NotDir);
            }
        }
        let ino = GHOST_BASE + self.next;
        self.next += 1;
        let now = Timestamp::now();
        self.nodes.insert(
            ino,
            GNode { parent, name: name.to_string(), kind, data: vec![], perm, atime: now, mtime: now, ctime: now, children: BTreeMap::new(), synthetic: false },
        );
        self.children_mut(parent)?.insert(name.to_string(), ino);
        self.dirty = true;
        Ok(ino)
    }

    fn remove_node(&mut self, ino: Ino) {
        if let Some(n) = self.nodes.remove(&ino) {
            for (_, c) in n.children {
                self.remove_node(c);
            }
        }
        self.dirty = true;
    }

    fn node_attr(&self, ino: Ino) -> FsResult<Attr> {
        let n = self.nodes.get(&ino).ok_or(FsError::Stale)?;
        Ok(Attr {
            ino,
            kind: n.kind,
            size: n.data.len() as u64,
            perm: n.perm,
            nlink: if n.kind == FileKind::Dir { 2 } else { 1 },
            uid: self.uid,
            gid: self.gid,
            atime: n.atime,
            mtime: n.mtime,
            ctime: n.ctime,
            used_bytes: 0,
        })
    }

    fn real_path(&self, ino: Ino) -> Option<String> {
        let root = self.inner.root_ino();
        let mut parts = vec![];
        let mut cur = ino;
        for _ in 0..512 {
            if cur == root {
                parts.reverse();
                return Some(format!("/{}", parts.join("/")));
            }
            let (p, n) = self.real_parent.get(&cur)?;
            parts.push(n.clone());
            cur = *p;
        }
        None
    }

    fn node_path(&self, ino: Ino) -> Option<String> {
        let n = self.nodes.get(&ino)?;
        let parent = if Self::is_ghost(n.parent) { self.node_path(n.parent)? } else { self.real_path(n.parent)? };
        Some(if parent == "/" { format!("/{}", n.name) } else { format!("{parent}/{}", n.name) })
    }

    fn top_category(&self, ino: Ino) -> Category {
        let mut cur = ino;
        let mut cat = Category::Other;
        while let Some(n) = self.nodes.get(&cur) {
            if let Some(c) = classify(&n.name) {
                cat = c;
            }
            if !Self::is_ghost(n.parent) {
                break;
            }
            cur = n.parent;
        }
        cat
    }

    /// All virtualised files (for the UI).
    pub fn entries(&self) -> Vec<GhostEntry> {
        let mut v: Vec<GhostEntry> = self
            .nodes
            .iter()
            .filter(|(_, n)| n.kind != FileKind::Dir && !n.synthetic)
            .filter_map(|(ino, n)| {
                Some(GhostEntry { path: self.node_path(*ino)?, size: n.data.len() as u64, category: self.top_category(*ino) })
            })
            .collect();
        v.sort_by(|a, b| a.path.cmp(&b.path));
        v
    }

    pub fn vault_bytes(&self) -> u64 {
        self.nodes.values().map(|n| n.data.len() as u64).sum()
    }

    pub fn purge(&mut self) {
        self.nodes.clear();
        self.dir_children.clear();
        self.dirty = true;
    }

    // ── vault persistence ──

    fn open_db(path: &Path) -> rusqlite::Result<rusqlite::Connection> {
        let c = rusqlite::Connection::open(path)?;
        c.execute_batch(
            "PRAGMA journal_mode=WAL;
             CREATE TABLE IF NOT EXISTS entries(path TEXT PRIMARY KEY, kind INTEGER NOT NULL, perm INTEGER NOT NULL,
                 mtime INTEGER NOT NULL, data BLOB NOT NULL);
             CREATE TABLE IF NOT EXISTS meta(key TEXT PRIMARY KEY, value INTEGER NOT NULL);",
        )?;
        Ok(c)
    }

    fn load_vault(&mut self) -> Result<(), String> {
        let Some(path) = self.vault_path.clone() else { return Ok(()) };
        if let Some(d) = path.parent() {
            std::fs::create_dir_all(d).map_err(|e| e.to_string())?;
        }
        let db = Self::open_db(&path).map_err(|e| e.to_string())?;
        self.blocked_total = db
            .query_row("SELECT value FROM meta WHERE key='blocked_total'", [], |r| r.get::<_, i64>(0))
            .unwrap_or(0) as u64;
        let mut stmt = db.prepare("SELECT path, kind, perm, mtime, data FROM entries ORDER BY length(path), path").map_err(|e| e.to_string())?;
        let rows: Vec<(String, i64, i64, i64, Vec<u8>)> = stmt
            .query_map([], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?)))
            .map_err(|e| e.to_string())?
            .filter_map(|r| r.ok())
            .collect();
        for (p, kind, perm, mtime, data) in rows {
            let comps: Vec<&str> = p.split('/').filter(|c| !c.is_empty()).collect();
            let Some((name, dirs)) = comps.split_last() else { continue };
            let mut cur = self.inner.root_ino();
            let mut ok = true;
            for c in dirs {
                if let Ok(g) = self.ghost_lookup(cur, c) {
                    cur = g;
                    continue;
                }
                match self.inner.lookup(cur, c) {
                    Ok(i) => {
                        self.real_parent.insert(i, (cur, c.to_string()));
                        cur = i;
                    }
                    Err(_) => {
                        ok = false;
                        break;
                    }
                }
            }
            if !ok {
                continue;
            }
            let kind = if kind == 1 { FileKind::Dir } else { FileKind::File };
            if let Ok(ino) = self.new_node(cur, name, kind, perm as u16) {
                let n = self.nodes.get_mut(&ino).unwrap();
                n.data = data;
                n.mtime = Timestamp { secs: mtime, nsecs: 0 };
            }
        }
        self.dirty = false;
        Ok(())
    }

    pub fn save_vault(&mut self) -> Result<(), String> {
        if !self.dirty {
            return Ok(());
        }
        let Some(path) = self.vault_path.clone() else {
            self.dirty = false;
            return Ok(());
        };
        let mut db = Self::open_db(&path).map_err(|e| e.to_string())?;
        let tx = db.transaction().map_err(|e| e.to_string())?;
        tx.execute("DELETE FROM entries", []).map_err(|e| e.to_string())?;
        {
            let mut ins = tx
                .prepare("INSERT OR REPLACE INTO entries(path, kind, perm, mtime, data) VALUES (?1, ?2, ?3, ?4, ?5)")
                .map_err(|e| e.to_string())?;
            for (ino, n) in &self.nodes {
                if n.synthetic {
                    continue;
                }
                if let Some(p) = self.node_path(*ino) {
                    ins.execute(rusqlite::params![p, (n.kind == FileKind::Dir) as i64, n.perm as i64, n.mtime.secs, n.data])
                        .map_err(|e| e.to_string())?;
                }
            }
        }
        tx.execute("INSERT OR REPLACE INTO meta(key, value) VALUES ('blocked_total', ?1)", [self.blocked_total as i64])
            .map_err(|e| e.to_string())?;
        tx.commit().map_err(|e| e.to_string())?;
        self.dirty = false;
        Ok(())
    }

    // ── real ↔ ghost moves ──

    fn read_all_real(&mut self, ino: Ino) -> FsResult<Vec<u8>> {
        let mut out = vec![];
        loop {
            let chunk = self.inner.read(ino, out.len() as u64, 1 << 20)?;
            if chunk.is_empty() {
                break;
            }
            out.extend(chunk);
        }
        Ok(out)
    }

    fn materialize(&mut self, g: Ino, parent: Ino, name: &str) -> FsResult<()> {
        let n = self.nodes.get(&g).cloned().ok_or(FsError::Stale)?;
        match n.kind {
            FileKind::Dir => {
                let d = self.inner.mkdir(parent, name, n.perm, self.uid, self.gid)?;
                for (cn, ci) in n.children.clone() {
                    self.materialize(ci, d, &cn)?;
                }
            }
            _ => {
                let f = self.inner.create(parent, name, n.perm, self.uid, self.gid)?;
                if !n.data.is_empty() {
                    self.inner.write(f, 0, &n.data)?;
                }
            }
        }
        Ok(())
    }

    fn purge_real_junk(&mut self, dir: Ino) -> FsResult<bool> {
        let entries = self.inner.readdir(dir)?;
        if entries.iter().any(|e| classify(&e.name).is_none()) {
            return Ok(false);
        }
        for e in entries {
            if e.kind == FileKind::Dir {
                self.purge_real_junk(e.ino)?;
                self.inner.rmdir(dir, &e.name)?;
            } else {
                self.inner.unlink(dir, &e.name)?;
            }
        }
        Ok(true)
    }
}

impl<F: FileSystem> FileSystem for GhostShield<F> {
    fn volume_info(&self) -> VolumeInfo {
        self.inner.volume_info()
    }
    fn statfs(&mut self) -> FsResult<FsStat> {
        self.inner.statfs()
    }
    fn root_ino(&self) -> Ino {
        self.inner.root_ino()
    }

    fn lookup(&mut self, parent: Ino, name: &str) -> FsResult<Ino> {
        if self.ghost_ctx(parent, name) {
            return self.ghost_lookup(parent, name);
        }
        let i = self.inner.lookup(parent, name)?;
        self.real_parent.insert(i, (parent, name.to_string()));
        Ok(i)
    }

    fn getattr(&mut self, ino: Ino) -> FsResult<Attr> {
        if Self::is_ghost(ino) {
            self.node_attr(ino)
        } else {
            self.inner.getattr(ino)
        }
    }

    fn setattr(&mut self, ino: Ino, set: &SetAttr) -> FsResult<Attr> {
        if !Self::is_ghost(ino) {
            return self.inner.setattr(ino, set);
        }
        let n = self.nodes.get_mut(&ino).ok_or(FsError::Stale)?;
        if let Some(sz) = set.size {
            if n.kind == FileKind::Dir {
                return Err(FsError::IsDir);
            }
            n.data.resize(sz as usize, 0);
        }
        if let Some(p) = set.perm {
            n.perm = p;
        }
        if let Some(t) = set.atime {
            n.atime = t;
        }
        if let Some(t) = set.mtime {
            n.mtime = t;
        }
        n.ctime = Timestamp::now();
        self.dirty = true;
        self.node_attr(ino)
    }

    fn read(&mut self, ino: Ino, offset: u64, len: u32) -> FsResult<Vec<u8>> {
        if !Self::is_ghost(ino) {
            return self.inner.read(ino, offset, len);
        }
        let n = self.nodes.get(&ino).ok_or(FsError::Stale)?;
        if n.kind == FileKind::Dir {
            return Err(FsError::IsDir);
        }
        let s = (offset as usize).min(n.data.len());
        let e = (s + len as usize).min(n.data.len());
        Ok(n.data[s..e].to_vec())
    }

    fn write(&mut self, ino: Ino, offset: u64, data: &[u8]) -> FsResult<u32> {
        if !Self::is_ghost(ino) {
            return self.inner.write(ino, offset, data);
        }
        let n = self.nodes.get_mut(&ino).ok_or(FsError::Stale)?;
        if n.kind == FileKind::Dir {
            return Err(FsError::IsDir);
        }
        n.synthetic = false;
        if offset > 64 << 20 {
            return Err(FsError::NoSpace);
        }
        let end = offset as usize + data.len();
        if n.data.len() < end {
            n.data.resize(end, 0);
        }
        n.data[offset as usize..end].copy_from_slice(data);
        n.mtime = Timestamp::now();
        self.dirty = true;
        Ok(data.len() as u32)
    }

    fn readdir(&mut self, dir: Ino) -> FsResult<Vec<DirEntry>> {
        if Self::is_ghost(dir) {
            let n = self.nodes.get(&dir).ok_or(FsError::Stale)?;
            if n.kind != FileKind::Dir {
                return Err(FsError::NotDir);
            }
            return Ok(n
                .children
                .iter()
                .map(|(name, ino)| DirEntry { name: name.clone(), ino: *ino, kind: self.nodes[ino].kind })
                .collect());
        }
        let mut v = self.inner.readdir(dir)?;
        if self.enabled {
            v.retain(|e| !self.intercept(&e.name));
        }
        for e in &v {
            if e.kind == FileKind::Dir {
                self.real_parent.insert(e.ino, (dir, e.name.clone()));
            }
        }
        if self.enabled {
            if let Some(c) = self.dir_children.get(&dir) {
                for (name, ino) in c {
                    if self.intercept(name) || self.nodes.get(ino).map(|n| n.synthetic).unwrap_or(false) {
                        v.push(DirEntry { name: name.clone(), ino: *ino, kind: self.nodes[ino].kind });
                    }
                }
            }
        }
        Ok(v)
    }

    fn create(&mut self, parent: Ino, name: &str, perm: u16, uid: u32, gid: u32) -> FsResult<Ino> {
        if self.ghost_ctx(parent, name) {
            let i = self.new_node(parent, name, FileKind::File, perm)?;
            self.blocked_total += 1;
            return Ok(i);
        }
        let i = self.inner.create(parent, name, perm, uid, gid)?;
        self.real_parent.insert(i, (parent, name.to_string()));
        Ok(i)
    }

    fn mkdir(&mut self, parent: Ino, name: &str, perm: u16, uid: u32, gid: u32) -> FsResult<Ino> {
        if self.ghost_ctx(parent, name) {
            let i = self.new_node(parent, name, FileKind::Dir, perm)?;
            self.blocked_total += 1;
            return Ok(i);
        }
        let i = self.inner.mkdir(parent, name, perm, uid, gid)?;
        self.real_parent.insert(i, (parent, name.to_string()));
        Ok(i)
    }

    fn symlink(&mut self, parent: Ino, name: &str, target: &str, uid: u32, gid: u32) -> FsResult<Ino> {
        if self.ghost_ctx(parent, name) {
            return Err(FsError::Perm);
        }
        self.inner.symlink(parent, name, target, uid, gid)
    }

    fn readlink(&mut self, ino: Ino) -> FsResult<String> {
        if Self::is_ghost(ino) {
            return Err(FsError::Invalid("not a symlink".into()));
        }
        self.inner.readlink(ino)
    }

    fn unlink(&mut self, parent: Ino, name: &str) -> FsResult<()> {
        if self.ghost_ctx(parent, name) {
            let i = self.ghost_lookup(parent, name)?;
            if self.nodes[&i].kind == FileKind::Dir {
                return Err(FsError::IsDir);
            }
            self.children_mut(parent)?.remove(name);
            self.remove_node(i);
            return Ok(());
        }
        self.inner.unlink(parent, name)
    }

    fn rmdir(&mut self, parent: Ino, name: &str) -> FsResult<()> {
        if self.ghost_ctx(parent, name) {
            let i = self.ghost_lookup(parent, name)?;
            let n = &self.nodes[&i];
            if n.kind != FileKind::Dir {
                return Err(FsError::NotDir);
            }
            if !n.children.is_empty() {
                return Err(FsError::NotEmpty);
            }
            self.children_mut(parent)?.remove(name);
            self.remove_node(i);
            return Ok(());
        }
        let target = self.inner.lookup(parent, name)?;
        if self.dir_children.get(&target).map(|c| c.values().any(|g| self.nodes.contains_key(g))).unwrap_or(false) && self.enabled {
            return Err(FsError::NotEmpty);
        }
        match self.inner.rmdir(parent, name) {
            Err(FsError::NotEmpty) if self.enabled => {
                // Only hidden pre-existing macOS junk left? Clean it from the disk and retry.
                if self.purge_real_junk(target)? {
                    self.inner.rmdir(parent, name)?;
                } else {
                    return Err(FsError::NotEmpty);
                }
            }
            r => r?,
        }
        if let Some(c) = self.dir_children.remove(&target) {
            for (_, g) in c {
                self.remove_node(g);
            }
        }
        self.real_parent.remove(&target);
        Ok(())
    }

    fn rename(&mut self, fp: Ino, fname: &str, tp: Ino, tname: &str) -> FsResult<()> {
        let from_ghost = self.ghost_ctx(fp, fname);
        let to_ghost = self.ghost_ctx(tp, tname);
        match (from_ghost, to_ghost) {
            (false, false) => {
                let moved = self.inner.lookup(fp, fname).ok();
                self.inner.rename(fp, fname, tp, tname)?;
                if let Some(m) = moved {
                    self.real_parent.insert(m, (tp, tname.to_string()));
                }
                Ok(())
            }
            (true, true) => {
                check_name(tname, 255)?;
                let g = self.ghost_lookup(fp, fname)?;
                if let Ok(existing) = self.ghost_lookup(tp, tname) {
                    if existing == g {
                        return Ok(());
                    }
                    let ek = self.nodes[&existing].kind;
                    let gk = self.nodes[&g].kind;
                    if ek == FileKind::Dir && !self.nodes[&existing].children.is_empty() {
                        return Err(FsError::NotEmpty);
                    }
                    if (ek == FileKind::Dir) != (gk == FileKind::Dir) {
                        return Err(if gk == FileKind::Dir { FsError::NotDir } else { FsError::IsDir });
                    }
                    self.children_mut(tp)?.remove(tname);
                    self.remove_node(existing);
                }
                self.children_mut(fp)?.remove(fname);
                self.children_mut(tp)?.insert(tname.to_string(), g);
                let n = self.nodes.get_mut(&g).unwrap();
                n.parent = tp;
                n.name = tname.to_string();
                n.ctime = Timestamp::now();
                self.dirty = true;
                Ok(())
            }
            (true, false) => {
                // ghost → real: write it out for real.
                let g = self.ghost_lookup(fp, fname)?;
                if let Ok(existing) = self.inner.lookup(tp, tname) {
                    if self.inner.getattr(existing)?.kind == FileKind::Dir {
                        self.inner.rmdir(tp, tname)?;
                    } else {
                        self.inner.unlink(tp, tname)?;
                    }
                }
                self.materialize(g, tp, tname)?;
                self.children_mut(fp)?.remove(fname);
                self.remove_node(g);
                Ok(())
            }
            (false, true) => {
                // real → ghost: pull the file into the vault and delete it from the disk.
                let r = self.inner.lookup(fp, fname)?;
                let a = self.inner.getattr(r)?;
                if a.kind != FileKind::File {
                    return Err(FsError::Perm);
                }
                let data = self.read_all_real(r)?;
                if let Ok(existing) = self.ghost_lookup(tp, tname) {
                    self.children_mut(tp)?.remove(tname);
                    self.remove_node(existing);
                }
                let g = self.new_node(tp, tname, FileKind::File, a.perm)?;
                self.nodes.get_mut(&g).unwrap().data = data;
                self.inner.unlink(fp, fname)?;
                self.blocked_total += 1;
                Ok(())
            }
        }
    }

    fn sync(&mut self) -> FsResult<()> {
        if let Err(e) = self.save_vault() {
            eprintln!("lumendisk: ghost vault save failed: {e}");
        }
        self.inner.sync()
    }
    fn dirty_state(&mut self) -> DirtyState {
        self.inner.dirty_state()
    }
    fn repair(&mut self) -> FsResult<String> {
        self.inner.repair()
    }
}

impl<F: FileSystem> Drop for GhostShield<F> {
    fn drop(&mut self) {
        let _ = self.save_vault();
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::block::{BlockDev, MemDev};
    use crate::vfs::ext4_fs;
    use std::sync::Arc;

    fn vol() -> Arc<dyn BlockDev> {
        let dev: Arc<dyn BlockDev> = Arc::new(MemDev::new(32 << 20));
        ext4_fs::format(dev.clone(), FsType::Ext4, "g").unwrap();
        dev
    }

    #[test]
    fn junk_never_reaches_disk_and_persists_in_vault() {
        let dev = vol();
        let vault = std::env::temp_dir().join(format!("ld-ghost-{}.db", std::process::id()));
        let _ = std::fs::remove_file(&vault);
        {
            let raw = ext4_fs::Ext4Fs::open(dev.clone(), false).unwrap();
            let mut g = GhostShield::new(raw, true, GhostRules::default(), MountDefaults::default(), Some(vault.clone()));
            let root = g.root_ino();
            let docs = g.mkdir(root, "Docs", 0o755, 0, 0).unwrap();
            let f = g.create(docs, "report.txt", 0o644, 0, 0).unwrap();
            g.write(f, 0, b"real data").unwrap();
            let ds = g.create(docs, ".DS_Store", 0o644, 0, 0).unwrap();
            g.write(ds, 0, b"Bud1-finder-state").unwrap();
            let ad = g.create(docs, "._report.txt", 0o644, 0, 0).unwrap();
            g.write(ad, 0, &[0x00, 0x05, 0x16, 0x07]).unwrap();
            let sp = g.mkdir(root, ".Spotlight-V100", 0o700, 0, 0).unwrap();
            let st = g.create(sp, "Store-V2", 0o600, 0, 0).unwrap();
            g.write(st, 0, &vec![7u8; 5000]).unwrap();
            g.mkdir(root, ".fseventsd", 0o700, 0, 0).unwrap();
            // Finder view
            let mut names: Vec<String> = g.readdir(docs).unwrap().into_iter().map(|e| e.name).collect();
            names.sort();
            assert_eq!(names, vec![".DS_Store", "._report.txt", "report.txt"]);
            assert_eq!(g.read(ds, 0, 100).unwrap(), b"Bud1-finder-state");
            assert_eq!(g.blocked_total, 5);
            assert_eq!(g.entries().len(), 3);
            // rename ghost->ghost (AppleDouble follows its file)
            g.rename(docs, "report.txt", docs, "final.txt").unwrap();
            g.rename(docs, "._report.txt", docs, "._final.txt").unwrap();
            g.sync().unwrap();
        }
        // Physical disk: no junk at all.
        let mut raw = ext4_fs::Ext4Fs::open(dev.clone(), false).unwrap();
        let root = raw.root_ino();
        let mut top: Vec<String> = raw.readdir(root).unwrap().into_iter().map(|e| e.name).collect();
        top.sort();
        assert_eq!(top, vec!["Docs", "lost+found"]);
        let docs = raw.lookup(root, "Docs").unwrap();
        let names: Vec<String> = raw.readdir(docs).unwrap().into_iter().map(|e| e.name).collect();
        assert_eq!(names, vec!["final.txt"]);
        drop(raw);
        // Next session: Finder gets its state back from the vault.
        let raw = ext4_fs::Ext4Fs::open(dev, false).unwrap();
        let mut g = GhostShield::new(raw, true, GhostRules::default(), MountDefaults::default(), Some(vault.clone()));
        let docs = g.lookup(root, "Docs").unwrap();
        let ds = g.lookup(docs, ".DS_Store").unwrap();
        assert_eq!(g.read(ds, 0, 100).unwrap(), b"Bud1-finder-state");
        assert!(g.lookup(docs, "._final.txt").is_ok());
        assert_eq!(g.blocked_total, 5);
        let sp = g.lookup(root, ".Spotlight-V100").unwrap();
        let st = g.lookup(sp, "Store-V2").unwrap();
        assert_eq!(g.getattr(st).unwrap().size, 5000);
        // Deleting a folder works even if pre-existing junk is hidden in it.
        let _ = std::fs::remove_file(&vault);
    }

    #[test]
    fn preexisting_junk_is_hidden_and_cleaned_on_rmdir() {
        let dev = vol();
        let mut raw = ext4_fs::Ext4Fs::open(dev.clone(), false).unwrap();
        let root = raw.root_ino();
        let d = raw.mkdir(root, "old", 0o755, 0, 0).unwrap();
        raw.create(d, ".DS_Store", 0o644, 0, 0).unwrap();
        raw.create(d, "._x", 0o644, 0, 0).unwrap();
        let mut g = GhostShield::new(raw, true, GhostRules::default(), MountDefaults::default(), None);
        assert!(g.readdir(d).unwrap().is_empty());
        g.rmdir(root, "old").unwrap();
        assert_eq!(g.lookup(root, "old"), Err(FsError::NotFound));
    }

    #[test]
    fn disabled_rules_pass_through() {
        let dev = vol();
        let raw = ext4_fs::Ext4Fs::open(dev.clone(), false).unwrap();
        let rules = GhostRules { ds_store: false, ..Default::default() };
        let mut g = GhostShield::new(raw, true, rules, MountDefaults::default(), None);
        let root = g.root_ino();
        let i = g.create(root, ".DS_Store", 0o644, 0, 0).unwrap();
        assert!(i < GHOST_BASE, "with the rule off .DS_Store must go to disk");
        let j = g.create(root, "._y", 0o644, 0, 0).unwrap();
        assert!(j >= GHOST_BASE);
    }
}

/// AppleDouble (v2) file holding only a FinderInfo with kHasCustomIcon set (folder flags).
pub fn appledouble_custom_icon() -> Vec<u8> {
    let mut v = Vec::with_capacity(82);
    v.extend_from_slice(&0x0005_1607u32.to_be_bytes()); // magic
    v.extend_from_slice(&0x0002_0000u32.to_be_bytes()); // version
    v.extend_from_slice(b"Mac OS X        "); // filler
    v.extend_from_slice(&2u16.to_be_bytes()); // entries
    // FinderInfo (id 9) at 50, len 32; resource fork (id 2) at 82, len 0
    for (id, off, len) in [(9u32, 50u32, 32u32), (2, 82, 0)] {
        v.extend_from_slice(&id.to_be_bytes());
        v.extend_from_slice(&off.to_be_bytes());
        v.extend_from_slice(&len.to_be_bytes());
    }
    let mut fi = [0u8; 32];
    fi[8..10].copy_from_slice(&0x0400u16.to_be_bytes()); // frFlags: kHasCustomIcon
    v.extend_from_slice(&fi);
    v
}
