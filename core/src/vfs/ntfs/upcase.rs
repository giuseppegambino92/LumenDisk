/// Build the 65536-entry default upcase table.
pub fn default_upcase() -> Vec<u16> {
    let mut t: Vec<u16> = (0..=0xFFFFu32).map(|c| c as u16).collect();
    for &(first, count, delta, step) in UPCASE_RUNS {
        for n in 0..count as u32 {
            let c = first as u32 + n * step as u32;
            if c < 0x10000 {
                t[c as usize] = (c as i32 + delta) as u16;
            }
        }
    }
    t
}

